"""Flow model registry: gate check, MLflow Model Registry, and GCP manifest.

Usage:
  python -m src.models.flow.registry            # check gates, register in Staging
  python -m src.models.flow.registry --promote  # move to Production
  python -m src.models.flow.registry --rollback # re-alias Production to previous version

Gate check: the latest MLflow run in stoa_flow_model must beat both thresholds in
configs/model.yaml before anything is promoted to Production. A failed gate exits 1
so CI can block deployment.

The Docker image push to GCP Artifact Registry happens in CI (GitHub Actions), not
here. This module only writes configs/model_registry.yaml as a pointer so the CI
job and Cloud Run know which model version to deploy.
"""

from __future__ import annotations

import argparse
import sys

import yaml

from src.ingest.common import REPO_ROOT, setup_logging

try:
    import mlflow
    import mlflow.tracking
except ImportError:  # mlflow optional until installed
    mlflow = None  # type: ignore[assignment]

MODEL_YAML = REPO_ROOT / "configs" / "model.yaml"
REGISTRY_YAML = REPO_ROOT / "configs" / "model_registry.yaml"
MODEL_NAME = "stoa-flow-model"
EXPERIMENT = "stoa_flow_model"


def find_best_run(
    experiment_name: str,
    mae_log_gate: float,
    coverage_low: float,
    coverage_high: float,
) -> str:
    """Return the run_id of the latest MLflow run that passes both gates.

    Raises ValueError when no qualifying run exists.
    """
    client = mlflow.tracking.MlflowClient()
    exp = client.get_experiment_by_name(experiment_name)
    if exp is None:
        raise ValueError(f"MLflow experiment {experiment_name!r} not found")

    runs = client.search_runs(
        experiment_ids=[exp.experiment_id],
        filter_string="attributes.status = 'FINISHED'",
        order_by=["start_time DESC"],
        max_results=50,
    )
    for run in runs:
        m = run.data.metrics
        ml = m.get("mae_log")
        cov = m.get("interval_coverage")
        ss_mae = m.get("space_syntax_mae_log")
        if ml is None or cov is None:
            continue
        if ss_mae is not None:
            improvement = (ss_mae - ml) / ss_mae * 100.0 if ss_mae > 0 else -1
            if improvement < mae_log_gate:
                continue
        if not (coverage_low <= cov <= coverage_high):
            continue
        return run.info.run_id

    raise ValueError(
        f"No finished run in {experiment_name!r} meets gates "
        f"(MAE-log improvement >= {mae_log_gate}%, coverage in [{coverage_low}, {coverage_high}])"
    )


def register(run_id: str, model_name: str = MODEL_NAME) -> str:
    """Register the model from run_id in the MLflow Model Registry. Returns the version."""
    result = mlflow.register_model(
        model_uri=f"runs:/{run_id}/model",
        name=model_name,
    )
    return result.version


def push_to_gcp(run_id: str, version: str, model_name: str = MODEL_NAME) -> None:
    """Write the model manifest to configs/model_registry.yaml.

    The actual Docker image is built and pushed by CI using this manifest.
    """
    client = mlflow.tracking.MlflowClient()
    mv = client.get_model_version(model_name, version)
    manifest = {
        "model_name": model_name,
        "version": version,
        "run_id": run_id,
        "model_uri": mv.source,
        "stage": mv.current_stage,
        "note": (
            "This file is written by src.models.flow.registry and read by CI "
            "to tag the Docker image pushed to GCP Artifact Registry."
        ),
    }
    REGISTRY_YAML.write_text(
        "# Generated by src/models/flow/registry.py — do not edit by hand.\n"
        + yaml.safe_dump(manifest, sort_keys=False)
    )


def promote(version: str, model_name: str = MODEL_NAME) -> None:
    """Transition the version from Staging to Production in MLflow Model Registry."""
    client = mlflow.tracking.MlflowClient()
    client.transition_model_version_stage(
        name=model_name,
        version=version,
        stage="Production",
        archive_existing_versions=True,
    )


def rollback(model_name: str = MODEL_NAME) -> None:
    """Re-alias Production to the most recent Archived version."""
    client = mlflow.tracking.MlflowClient()
    archived = client.search_model_versions(
        filter_string=f"name='{model_name}'",
    )
    archived = [mv for mv in archived if mv.current_stage == "Archived"]
    if not archived:
        raise ValueError(f"No archived versions of {model_name!r} to roll back to")
    archived.sort(key=lambda mv: int(mv.version), reverse=True)
    prev = archived[0]
    client.transition_model_version_stage(
        name=model_name,
        version=prev.version,
        stage="Production",
        archive_existing_versions=True,
    )
    print(f"Rolled back {model_name} Production to version {prev.version}")


def main() -> None:
    setup_logging()
    ap = argparse.ArgumentParser()
    ap.add_argument("--promote", action="store_true", help="Move to Production")
    ap.add_argument(
        "--rollback", action="store_true", help="Re-alias Production to previous version"
    )
    args = ap.parse_args()

    mlflow.set_tracking_uri(f"file:{REPO_ROOT / 'mlruns'}")

    if args.rollback:
        rollback()
        return

    cfg = yaml.safe_load(MODEL_YAML.read_text())
    gates = cfg["gates"]

    try:
        run_id = find_best_run(
            EXPERIMENT,
            gates["mae_log_improvement_pct"],
            gates["interval_coverage_low"],
            gates["interval_coverage_high"],
        )
    except ValueError as exc:
        print(f"Gate failed: {exc}", file=sys.stderr)
        sys.exit(1)

    version = register(run_id)
    stage = "Production" if args.promote else "Staging"
    if args.promote:
        promote(version)
    push_to_gcp(run_id, version)
    print(f"Registered {MODEL_NAME} version {version} → {stage} (run {run_id})")


if __name__ == "__main__":
    main()
